"""Table 1 as LaTeX, driven by the same readers as the Markdown tables.

The numbers come from runs/make_mdtables.py, so the .tex and the .md cannot
drift apart: regenerate both after a sweep and they agree by construction.

    python runs/make_latex.py            # -> mdtable/table1_main.tex
    python runs/make_latex.py --out x.tex
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from runs.make_mdtables import CITIES, METHODS, ceiling, per_seed  # noqa: E402

# Two metrics, reported separately: the proposed method's lead is larger on the
# rate than on the value, because the orders it adds are the ones the baselines
# could not reach -- further out, tighter, and worth less each.
BLOCKS = [
    ("on_time_gmv", r"On-time GMV ($\times 10^3$)", 1e-3, 1),
    ("on_time_order_rate", r"On-time fulfilment rate $|T|/|G|$", 1.0, 3),
]
SHORT = {
    "hongkong": "HK", "london": "LDN", "lade_cq": "CQ", "lade_sh": "SH",
    "meituan-ssn": "SSN", "meituan-ssa": "SSA", "meituan-sln": "SLN",
    "meituan-san": "SAN", "meituan-lsn": "LSN", "meituan-asn": "ASN",
}


def cell(rec_city: str, algo: str, key: str) -> tuple[float, float] | None:
    got = per_seed(rec_city, algo, key)
    values = [got[seed] for seed in (42, 43, 44) if seed in got]
    if len(values) != 3:
        return None
    return float(np.mean(values)), float(np.std(values, ddof=1))


def fmt(value: float, scale: float, digits: int) -> str:
    out = f"{value * scale:.{digits}f}"
    return out.lstrip("0") if digits == 3 else out      # .641 reads better than 0.641


def build() -> str:
    cities = [(label, rec) for label, _, rec in CITIES]
    out: list[str] = [
        r"% Generated by runs/make_latex.py -- do not edit the numbers by hand.",
        r"% Needs booktabs and multirow. The gain row is F2 over the strongest",
        r"% baseline of that column, which is underlined; it is L2 on every city.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\caption{Held-out results on ten scenarios, three seeds each. Each entry is the"
        r" mean over the city's test instances with the seed standard deviation as a"
        r" subscript. The strongest baseline per column is \underline{underlined}; the"
        r" last row of each block is the proposed method's gain over it. The lead is"
        r" larger on the fulfilment rate than on the value: the orders the proposed"
        r" method adds are the ones the baselines could not reach, which are worth"
        r" less each.}",
        r"\label{tab:main}",
        r"\small",
        r"\setlength{\tabcolsep}{3.2pt}",
        r"\begin{tabular}{l" + "r" * len(cities) + "}",
        r"\toprule",
        "Method & " + " & ".join(SHORT.get(c, c) for c, _ in cities) + r" \\",
    ]

    ceiling_row = [ceiling(inst) for _, inst, _ in CITIES]
    out.append(r"\midrule")
    out.append(r"\textit{total order value} ($\times 10^3$) & "
               + " & ".join(f"{v * 1e-3:.1f}" for v in ceiling_row) + r" \\")

    for key, title, scale, digits in BLOCKS:
        values = {algo: [cell(rec, algo, key) for _, rec in cities] for algo, _ in METHODS}
        best_baseline = []
        for index in range(len(cities)):
            pool = {algo: v[index][0] for algo, v in values.items()
                    if algo != "F2_Separable" and v[index] is not None}
            best_baseline.append(max(pool, key=pool.get) if pool else None)

        out.append(r"\midrule")
        out.append(r"\multicolumn{%d}{l}{\textit{%s}} \\" % (len(cities) + 1, title))
        out.append(r"\midrule")
        for algo, label in METHODS:
            row = []
            for index, _ in enumerate(cities):
                got = values[algo][index]
                if got is None:
                    row.append("--")
                    continue
                mean, sd = got
                body = fmt(mean, scale, digits)
                sub = fmt(sd, scale, digits) or "0"
                entry = f"${body}_{{{sub}}}$"
                if algo == best_baseline[index]:
                    entry = r"\underline{" + entry + "}"
                if algo == "F2_Separable":
                    entry = r"\textbf{" + entry + "}"
                row.append(entry)
            out.append(f"{label} & " + " & ".join(row) + r" \\")

        gains = []
        for index, _ in enumerate(cities):
            mine = values["F2_Separable"][index]
            ref = values[best_baseline[index]][index] if best_baseline[index] else None
            gains.append(None if (mine is None or ref is None)
                         else 100.0 * (mine[0] / ref[0] - 1.0))
        out.append(r"\cmidrule(lr){1-%d}" % (len(cities) + 1))
        out.append(r"\textit{gain over best baseline} & "
                   + " & ".join("--" if g is None else f"{g:+.1f}\\%" for g in gains)
                   + r" \\")
        clean = [g for g in gains if g is not None]
        if clean:
            # the summary a reader of the paper will quote, kept next to the row
            # it summarises so the two cannot disagree
            out.append(f"% {len(clean)} cities: mean {np.mean(clean):+.2f}pct, "
                       f"median {np.median(clean):+.2f}pct, "
                       f"range {min(clean):+.2f}pct to {max(clean):+.2f}pct")

    out += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="mdtable/table1_main.tex")
    args = parser.parse_args()
    path = Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build())
    print(f"written {path}")


if __name__ == "__main__":
    main()
